#!/usr/bin/env python3
"""Generate the V5 crypt data module for the engine from KRCG card data.

Static card data is generated, never hand-typed (DESIGN §4.5). Output:
`crates/engine/src/crypt.rs` — the 200 V5 vampires and the owner-added
ones (id, printed name, capacity, group, clan, sect, title, advanced), the 14 full-size precon crypts and the
14 New Blood mini-starter crypts.

Usage: python3 scripts/gen_crypt.py [path/to/vtes.json] > crates/engine/src/crypt.rs
       python3 scripts/gen_crypt.py [path/to/vtes.json] --check crates/engine/src/crypt.rs
Downloads https://static.krcg.org/data/vtes.json if no path is given.
"""
import json
import os
import re
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from window_matrix import ADDED_CARDS, anniversary_decks, pool_order, sabbat_decks  # noqa: E402

V5_SETS = [
    "Fifth Edition", "Fifth Edition (Anarch)", "Fifth Edition (Companion)",
    "New Blood", "New Blood II", "New Blood III",
    "Fall of London", "Shadows of Berlin", "Echoes of Gehenna",
]
FULL_PRECON_SETS = ["Fifth Edition", "Fifth Edition (Anarch)", "Fifth Edition (Companion)"]
MINI_PRECON_SETS = ["New Blood", "New Blood II", "New Blood III"]

# Title is the card-text prefix (rulebook "Vampiric Sects"): sect, then an
# optional title. Prince/Baron/Archbishop of a city contest by city;
# Justicar and Inner Circle by clan; primogen is not unique.
# A clan named in a title, in its V5 form (rules-digest §1: Kasim Bayar's
# "Assamite Justicar" is the Banu Haqim Justicar's title).
V5_CLAN = {"Assamite": "Banu Haqim"}

# Some advanced printings open with "Advanced, " (Alan Sovereign, Jessica):
# the crypt's `adv` flag already says so.
TITLE = re.compile(
    r"^(?:Advanced, )?(Camarilla|Anarch|Independent|Sabbat|Laibon)"
    r"(?: (Prince|Baron|Archbishop) of ((?:[^:.]|\.(?=\w))+)| (primogen)| (\w+) Justicar"
    r"| (\w+) Inner Circle| (bishop|cardinal|priscus|regent|magaji))?[:.]"
)


def parse(card):
    # An imbued has no sect nor title (rulebook "Appendix: Imbued Rules").
    if "Imbued" in card["types"]:
        return None, "Title::None"
    m = TITLE.match(card["card_text"])
    if not m:
        raise SystemExit(f"cannot parse sect/title of {card['name']}: {card['card_text'][:80]}")
    sect = m.group(1)
    if m.group(2):
        # "Washington, D.C.": an abbreviation keeps its last dot.
        city = m.group(3) + ("." if re.search(r"\b[A-Z]\.[A-Z]$", m.group(3)) else "")
        title = f'Title::{m.group(2)}("{city}")'
    elif m.group(4):
        title = "Title::Primogen"
    elif m.group(5):
        title = f'Title::Justicar("{V5_CLAN.get(m.group(5), m.group(5))}")'
    elif m.group(6):
        title = f'Title::InnerCircle("{V5_CLAN.get(m.group(6), m.group(6))}")'
    elif m.group(7):
        title = f"Title::{m.group(7).capitalize()}"
    else:
        # "Independent. 2 votes (titled):" (Scout Youngwood; Karl Schrekt
        # Camarilla).
        # "Independent: The Baron has 2 votes (titled)."
        votes = re.match(r"^(?:Camarilla|Anarch|Independent|Sabbat)(?:\. |: [^.:]* has )"
                         r"(\d) votes? \(titled\)", card["card_text"])
        title = f"Title::Votes({votes.group(1)})" if votes else "Title::None"
    return sect, title


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(cards):
    vamps = pool_order(
        [c for c in cards if {"Vampire", "Imbued"} & set(c.get("types", []))
         and (set(V5_SETS) & set(c.get("ordered_sets", [])) or c["id"] in ADDED_CARDS)],
        key=lambda c: (c["_name"], c["name"]))
    index = {c["name"]: i for i, c in enumerate(vamps)}
    out = []
    out.append("//! V5 crypt data — GENERATED by scripts/gen_crypt.py from KRCG vtes.json.")
    out.append("//! Do not edit by hand; regenerate and check with `--check`.")
    out.append("")
    out.append("/// Sect printed on the card (rulebook \"Vampiric Sects\").")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    out.append("pub enum Sect {")
    out.append("    Camarilla,")
    out.append("    Anarch,")
    out.append("    Independent,")
    out.append("    Sabbat,")
    out.append("    /// A legacy sect (rulebook \"Other Vampire Sects\").")
    out.append("    Laibon,")
    out.append("}")
    out.append("")
    out.append("/// A title, printed or granted by a card. Prince, Baron and Archbishop of the")
    out.append("/// same city contest each other; each clan's Justicar and Inner Circle")
    out.append("/// member is unique; primogen is not unique. `Independent`: a unique")
    out.append("/// Independent title a card names, worth its votes (Saulot's Guiding")
    out.append("/// Wisdom); no V5 vampire prints one.")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    out.append("pub enum Title {")
    out.append("    None,")
    out.append("    Primogen,")
    out.append("    Prince(&'static str),")
    out.append("    Baron(&'static str),")
    out.append("    Justicar(&'static str),")
    out.append("    InnerCircle(&'static str),")
    out.append("    Archbishop(&'static str),")
    out.append("    /// Sabbat titles that are not unique (bishop 1 vote, cardinal 3; a")
    out.append("    /// priscus votes in the prisci block) and the unique regent (4).")
    out.append("    Bishop,")
    out.append("    Cardinal,")
    out.append("    Priscus,")
    out.append("    Regent,")
    out.append("    /// The Laibon magaji: 2 votes, not unique (rulebook \"Laibon\").")
    out.append("    Magaji,")
    out.append("    /// \"n votes (titled)\" printed on an Independent vampire (Arishat,")
    out.append("    /// Scout Youngwood): a title worth n votes, not unique.")
    out.append("    Votes(u8),")
    out.append("    Independent {")
    out.append("        name: &'static str,")
    out.append("        votes: u8,")
    out.append("    },")
    out.append("    /// A unique Laibon title a card names, worth its votes (Osebo Kholo).")
    out.append("    Laibon {")
    out.append("        name: &'static str,")
    out.append("        votes: u8,")
    out.append("    },")
    out.append("}")
    out.append("")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    out.append("pub struct CryptCard {")
    out.append("    pub id: u32,")
    out.append("    /// Printed name: the contest identity (the `(Gn)` suffix is KRCG's).")
    out.append("    pub name: &'static str,")
    out.append("    pub capacity: u8,")
    out.append("    /// Its crypt group; 0 for a vampire of any group (Anarch Convert).")
    out.append("    pub group: u8,")
    out.append("    /// The clan; an imbued's creed.")
    out.append("    pub clan: &'static str,")
    out.append("    /// Disciplines as printed: lower case = basic, upper case = superior;")
    out.append("    /// an imbued's virtues.")
    out.append("    pub disciplines: &'static [&'static str],")
    out.append("    /// `None` for an imbued.")
    out.append("    pub sect: Option<Sect>,")
    out.append("    /// An imbued (rulebook \"Appendix: Imbued Rules\"): a mortal ally, its")
    out.append("    /// capacity its cost and starting life.")
    out.append("    pub imbued: bool,")
    out.append("    pub title: Title,")
    out.append("    /// The title an advanced vampire holds only merged (\"[MERGED] Baron of")
    out.append("    /// London\", Appolonius): it takes precedence over the printed one.")
    out.append("    pub merged_title: Option<Title>,")
    out.append("    /// An advanced vampire (KRCG `adv`): the same vampire as its base")
    out.append("    /// card for contests (rulebook \"Advanced Vampires\").")
    out.append("    pub adv: bool,")
    out.append("    /// The Sabbat path printed on the vampire (KRCG `path`), the one it")
    out.append("    /// follows as it enters play.")
    out.append("    pub path: Option<&'static str>,")
    out.append("    /// \"Infernal.\": it does not unlock as normal; its controller may burn")
    out.append("    /// 1 pool in their unlock phase to unlock it (rulebook \"Infernal\").")
    out.append("    pub infernal: bool,")
    out.append("    /// \"Black Hand.\" (Elimelech): a trait cards read.")
    out.append("    pub black_hand: bool,")
    out.append("    /// \"Seraph.\" (Appius Claudius Corvus): a Black Hand trait, not a")
    out.append("    /// title (KRCG gives none); Tattoo Signal requires one.")
    out.append("    pub seraph: bool,")
    out.append("    /// Unique, unless printed \"Non-unique.\" (Valkyrie) or \"Tupdogs are not")
    out.append("    /// unique.\" (Tupdog): copies of a")
    out.append("    /// non-unique vampire do not contest.")
    out.append("    pub unique: bool,")
    out.append("    /// \"Blood cursed.\" (Alu, Wise Frog): it cannot commit diablerie")
    out.append("    /// (rulebook \"Traits\").")
    out.append("    pub blood_cursed: bool,")
    out.append("    /// \"Scarce.\" (Le Dinh Tho): influenced out, 3 pool burned for each")
    out.append("    /// vampire of its clan already controlled (rulebook \"Traits\").")
    out.append("    pub scarce: bool,")
    out.append("    /// \"Sterile.\" (Effie Lowery): it cannot perform actions to put new")
    out.append("    /// vampires in play (rulebook \"Traits\").")
    out.append("    pub sterile: bool,")
    out.append("    /// \"Red List.\" (Enkidu, The Noah): any Methuselah may mark it in")
    out.append("    /// their master phase and enter combat with it (rulebook \"Traits\").")
    out.append("    pub red_list: bool,")
    out.append("    /// A Blood Brother's printed circle (\"Torrance Circle:\", \"Kiev")
    out.append("    /// circle.\"); `None`: a circle of one (LSJ 20020609), New Blood's")
    out.append("    /// chosen as he enters play.")
    out.append("    pub circle: Option<&'static str>,")
    out.append("    /// \"Tremere slave\" (Porphyry, Tupdog): the clan it is enslaved to")
    out.append("    /// (rulebook \"Slave\").")
    out.append("    pub slave: Option<&'static str>,")
    out.append("}")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append(f"pub static CRYPT: [CryptCard; {len(vamps)}] = [")
    for c in vamps:
        sect, title = parse(c)
        out.append("    CryptCard {")
        out.append(f"        id: {c['id']},")
        out.append(f"        name: {rust_str(c['_name'])},")
        out.append(f"        capacity: {c['capacity']},")
        out.append(f"        group: {0 if c['group'] == 'ANY' else int(c['group'])},")
        out.append(f"        clan: {rust_str(c['clans'][0])},")
        # Flight is printed in the text, not KRCG's disciplines (Tupdog,
        # Verbruch): a superior Discipline the cards requiring [FLIGHT] read.
        flight = ["FLIGHT"] if "Flight [FLIGHT]" in c["card_text"] else []
        disc = ", ".join(rust_str(d) for d in c.get("disciplines", []) + flight)
        out.append(f"        disciplines: &[{disc}],")
        out.append(f"        sect: {f'Some(Sect::{sect})' if sect else 'None'},")
        out.append(f"        imbued: {'true' if 'Imbued' in c['types'] else 'false'},")
        out.append(f"        title: {title},")
        merged = re.search(r"\[MERGED\] (Prince|Baron|Archbishop) of ((?:[^:.]|\.(?=\w))+)[:.]", c["card_text"])
        out.append(f"        merged_title: {f'Some(Title::{merged.group(1)}({rust_str(merged.group(2))}))' if merged else 'None'},")
        out.append(f"        adv: {'true' if c.get('adv') else 'false'},")
        path = f"Some({rust_str(c['path'])})" if c.get("path") else "None"
        out.append(f"        path: {path},")
        text = c["card_text"]
        flag = lambda b: "true" if b else "false"
        out.append(f"        infernal: {flag(re.search(r'(^|[.:] )Infernal\.', text))},")
        out.append(f"        black_hand: {flag(re.search(r'(^|[.:] )Black Hand[.:]', text))},")
        out.append(f"        seraph: {flag(re.search(r'(^|[.:] )Seraph[.:]', text))},")
        # "Non-unique." (Valkyrie) or "Tupdogs are not unique." (Tupdog).
        out.append(f"        unique: {flag(not re.search(r'(^|[.:] )(Non-unique|[A-Z]\w*s are not unique)\.', text))},")
        out.append(f"        blood_cursed: {flag(re.search(r'(^|[.:] )Blood cursed\.', text, re.I))},")
        out.append(f"        scarce: {flag(re.search(r'(^|[.:] )Scarce\.', text))},")
        out.append(f"        sterile: {flag(re.search(r'(^|[.:] )Sterile\.', text))},")
        out.append(f"        red_list: {flag(re.search(r'(^|[.:] )Red List[.:]', text))},")
        circle = "Blood Brother" in c["clans"] and re.search(r"(?:^|[.:] )([A-Z][a-z]+(?: City)?) [Cc]ircle[.:]", text)
        out.append(f"        circle: {f'Some({rust_str(circle.group(1))})' if circle else 'None'},")
        slave = re.search(r"(?:^|[.:] )([A-Z]\w+(?: antitribu)?) slave[.:]", text)
        out.append(f"        slave: {f'Some({rust_str(slave.group(1))})' if slave else 'None'},")
        out.append("    },")
    out.append("];")
    out.append("")
    precon_table(out, vamps, lambda c: index[c["name"]], FULL_PRECON_SETS, "PRECONS", [
        "/// The 14 full-size preconstructed crypts (12 cards each) as",
        "/// (name, [(CRYPT index, copies)]).",
    ], 12)
    out.append("")
    precon_table(out, vamps, lambda c: index[c["name"]], MINI_PRECON_SETS, "MINI_PRECONS", [
        "/// The 14 New Blood mini-starter crypts (6 cards each) as",
        "/// (name, [(CRYPT index, copies)]).",
    ], 6)
    out.append("")
    ids = {c["id"]: i for i, c in enumerate(vamps)}
    anniversary_table(out, cards, ids, "ANNIVERSARY_PRECONS", [
        "/// The anniversary decks' crypts (12 cards each; reviewed decklists,",
        "/// `window_matrix.ANNIVERSARY_DECKS`) as (name, [(CRYPT index, copies)]).",
    ])
    out.append("")
    anniversary_table(out, cards, ids, "SABBAT_PRECONS", [
        "/// The Sabbat V5 precons' crypts (12 cards each) fully in the pool, by deck",
        "/// name, as (name, [(CRYPT index, copies)]).",
    ], sabbat_decks)
    return "\n".join(out) + "\n"


def anniversary_table(out, cards, ids, name, doc, source=anniversary_decks):
    """The `source` decks' cards found in `ids` (this table's side)."""
    decks = source(cards)
    out.extend(doc)
    out.append("#[rustfmt::skip]")
    out.append(f"pub static {name}: [(&str, &[(u16, u8)]); {len(decks)}] = [")
    for deck, s, entries in decks:
        body = ", ".join(f"({i}, {k})" for i, k in sorted((ids[c], k) for c, k in entries.items() if c in ids))
        out.append(f"    ({rust_str(deck + ' (' + s + ')')}, &[{body}]),")
    out.append("];")


def precon_table(out, cards, index_of, sets, name, doc, size=None):
    """One table of preconstructed decks from `sets`, sorted by (set, deck)."""
    precons = {}
    for c in cards:
        for s, entries in c["sets"].items():
            if s not in sets:
                continue
            for e in entries:
                if "precon" in e:
                    precons.setdefault((s, e["precon"]), []).append((index_of(c), e["copies"]))
    precons = sorted(precons.items())
    out.extend(doc)
    out.append("#[rustfmt::skip]")
    out.append(f"pub static {name}: [(&str, &[(u16, u8)]); {len(precons)}] = [")
    for (s, p), entries in precons:
        if size:
            total = sum(k for _, k in entries)
            assert total == size, (s, p, total)
        body = ", ".join(f"({i}, {k})" for i, k in sorted(entries))
        out.append(f"    ({rust_str(p + ' (' + s + ')')}, &[{body}]),")
    out.append("];")


def main():
    args = sys.argv[1:]
    check = None
    if "--check" in args:
        i = args.index("--check")
        check = args[i + 1]
        del args[i:i + 2]
    if args:
        cards = json.load(open(args[0]))
    else:
        with urllib.request.urlopen("https://static.krcg.org/data/vtes.json") as f:
            cards = json.load(f)
    text = generate(cards)
    if check:
        if open(check).read() != text:
            print(f"{check} differs from generated output", file=sys.stderr)
            sys.exit(1)
        print(f"# {check} is up to date", file=sys.stderr)
        return
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
