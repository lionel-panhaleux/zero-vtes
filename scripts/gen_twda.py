#!/usr/bin/env python3
"""Generate the TWDA decklist module for the engine: every tournament-winning
deck of the KRCG TWDA whose cards are all in the engine pool (DESIGN §3).

The pool and its indices are read from the generated tables themselves
(`crypt.rs`, `library.rs`: one `id:` line per card, in table order), so this
runs after gen_crypt.py and gen_library.py; adding cards to the pool and
regenerating picks up the decks they complete.

Versions of one deck are capped (owner, 2026-09-28), so training does not
face some archetypes far more than others: two decks sharing more than
`SAME_CRYPT` of their crypt (copies, over the smaller crypt; generic
vampires such as Anarch Convert ignored) are versions of the same deck. The
precons come first, each the first version of its own; then TWDA decks by
event size (players), then the newest, each kept if its deck has fewer than
`VERSIONS` versions so far and its library shares at most `SAME_LIBRARY`
(copies, over the larger library) with every version kept. Decks are
written in TWDA order (as the archive lists them). Output:
`crates/engine/src/twda.rs`.

Usage: python3 scripts/gen_twda.py [path/to/twda.json] > crates/engine/src/twda.rs
       python3 scripts/gen_twda.py [path/to/twda.json] --check crates/engine/src/twda.rs
Downloads https://static.krcg.org/data/twda.json if no path is given.
"""
import json
import os
import re
import sys
import urllib.request

SAME_CRYPT = 0.25
VERSIONS = 3
SAME_LIBRARY = 0.5
# Generic vampires any deck may run: not counted in crypt similarity.
GENERIC_CRYPT = {200076}  # Anarch Convert

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "crates", "engine", "src")


def table_ids(path, table):
    """KRCG ids of a generated table, in index order."""
    text = open(path).read()
    start = text.index(f"pub static {table}:")
    end = text.index("\n];", start)
    return [int(i) for i in re.findall(r"^        id: (\d+),", text[start:end], re.M)]


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def entries(cards, index):
    """(index, copies) sorted by index, or None if a card is not in the pool."""
    out = {}
    for c in cards:
        if c["id"] not in index:
            return None
        out[index[c["id"]]] = out.get(index[c["id"]], 0) + c["count"]
    return sorted(out.items())


def shared(x, y):
    y = dict(y)
    return sum(min(n, y.get(i, 0)) for i, n in x)


def size(x):
    return sum(n for _, n in x)


def precons():
    """The precons' (crypt, library) from the generated tables."""
    def table(path, name):
        text = open(path).read()
        start = text.index(f"pub static {name}:")
        body = text[start:text.index("\n];", start)]
        return [[(int(i), int(n)) for i, n in re.findall(r"\((\d+), (\d+)\)", line)]
                for line in body.splitlines() if line.startswith("    (")]
    return list(zip(table(os.path.join(SRC, "crypt.rs"), "PRECONS"),
                    table(os.path.join(SRC, "library.rs"), "PRECON_LIBRARIES")))


def generate(twda):
    crypt_ids = table_ids(os.path.join(SRC, "crypt.rs"), "CRYPT")
    crypt = {i: k for k, i in enumerate(crypt_ids)}
    generic = {k for k, i in enumerate(crypt_ids) if i in GENERIC_CRYPT}

    def same_deck(a, b):
        a = [(i, n) for i, n in a if i not in generic]
        b = [(i, n) for i, n in b if i not in generic]
        return shared(a, b) > SAME_CRYPT * max(1, min(size(a), size(b)))

    library = {i: k for k, i in enumerate(table_ids(os.path.join(SRC, "library.rs"), "LIBRARY"))}
    decks = []
    for d in twda:
        c = entries(d["crypt"]["cards"], crypt)
        lib = [card for section in d["library"].get("cards", []) for card in section.get("cards", [])]
        li = entries(lib, library)
        if c is None or li is None:
            continue
        # Tournament-legal sizes only (tournament rules: crypt 12+, library 60–90).
        if sum(n for _, n in c) < 12 or not 60 <= sum(n for _, n in li) <= 90:
            continue
        name = f"{d.get('name') or 'Unnamed'} ({d['event']}, {d['date']})"
        decks.append((name, d["id"], c, li, d.get("players_count") or 0, d["date"]))
    kept = precons()  # (crypt, library)
    keep = set()
    for deck in sorted(decks, key=lambda x: (x[4], x[5]), reverse=True):
        versions = [k for k in kept if same_deck(deck[2], k[0])]
        if len(versions) >= VERSIONS:
            continue
        if any(shared(deck[3], k[1]) > SAME_LIBRARY * max(size(deck[3]), size(k[1])) for k in versions):
            continue
        kept.append((deck[2], deck[3]))
        keep.add(deck[1])
    decks = [deck for deck in decks if deck[1] in keep]
    out = [
        "//! TWDA decklists fully in the engine pool — GENERATED by scripts/gen_twda.py",
        "//! from KRCG twda.json and the generated crypt/library tables. Do not edit by",
        "//! hand; regenerate and check with `--check`.",
        "",
        "/// (name (event, date), TWDA id, crypt, library): crypt and library as",
        "/// (CRYPT / LIBRARY index, copies).",
        "pub type Decklist = (",
        "    &'static str,",
        "    &'static str,",
        "    &'static [(u16, u8)],",
        "    &'static [(u16, u8)],",
        ");",
        "",
        "/// The decks, in TWDA order.",
        "#[rustfmt::skip]",
        f"pub static TWDA: [Decklist; {len(decks)}] = [",
    ]
    for name, tid, c, li, _, _ in decks:
        body_c = ", ".join(f"({i}, {n})" for i, n in c)
        body_l = ", ".join(f"({i}, {n})" for i, n in li)
        out.append(f"    ({rust_str(name)}, {rust_str(tid)}, &[{body_c}], &[{body_l}]),")
    out.append("];")
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    check = None
    if "--check" in args:
        i = args.index("--check")
        check = args[i + 1]
        del args[i:i + 2]
    if args:
        twda = json.load(open(args[0]))
    else:
        with urllib.request.urlopen("https://static.krcg.org/data/twda.json") as f:
            twda = json.load(f)
    text = generate(twda)
    if check:
        if open(check).read() != text:
            print(f"{check} differs from generated output", file=sys.stderr)
            sys.exit(1)
        print(f"# {check} is up to date", file=sys.stderr)
        return
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
